// Zone Management
// Zone points are normalized to 0..1 relative to the video frame.
export const getZones = (cameraId) => {
  return apiClient.get("/zone/", { params: { camera_id: cameraId } });
};

// Fetch all zones across all cameras, with the camera name attached
export const getZonesList = async () => {
  const [zonesResponse, camerasResponse] = await Promise.all([
    apiClient.get("/zone/"),
    getCamerasList(),
  ]);
  const cameraNames = Object.fromEntries(
    (camerasResponse.data.cameras || []).map((camera) => [camera.id, camera.name])
  );
  const zones = (zonesResponse.data.zones || []).map((zone) => ({
    ...zone,
    cameraId: zone.video_camera_id,
    cameraName: cameraNames[zone.video_camera_id],
  }));
  return { data: { zones } };
};

export const createZone = ({ name, cameraId, cameraName, points }) => {
  return apiClient.post("/zone/", {
    zone_name: name,
    camera_id: cameraId,
    camera_name: cameraName,
    points,
  });
};

export const deleteZone = (zoneId) => {
  return apiClient.delete("/zone/", { data: { zone_id: zoneId } });
};

// Alert Rule Management
export const getAlertRules = () => {
  return apiClient.get("/alert-rules/");
};

export const getAlertRulesForCamera = (cameraId) => {
  return apiClient.get(`/alert-rules/camera/${cameraId}`);
};

export const createAlertRule = (ruleData) => {
  // Ensure conditions_json is stringified if the backend expects a string
  const dataToSend = {
    ...ruleData,
    conditions_json: JSON.stringify(ruleData.conditions_json),
  };
  return apiClient.post("/alert-rules/", dataToSend);
};

export const updateAlertRule = (ruleId, ruleData) => {
  // Ensure conditions_json is stringified if it exists and the backend expects a string
  const dataToSend = { ...ruleData };
  if (dataToSend.conditions_json) {
    dataToSend.conditions_json = JSON.stringify(dataToSend.conditions_json);
  }
  return apiClient.put(`/alert-rules/${ruleId}`, dataToSend);
};

export const deleteAlertRule = (ruleId) => {
  return apiClient.delete(`/alert-rules/${ruleId}`);
};
