import axios from "axios";
import { SERVER_URL } from "../utils/constants";

// Axios instance with base configuration
const apiClient = axios.create({
  baseURL: SERVER_URL,
  headers: {
    "Content-Type": "application/json",
  },
  // Add withCredentials for CORS with credentials
  withCredentials: true,
});

// Automatically add auth token to requests if available
apiClient.interceptors.request.use((config) => {
  const token = localStorage.getItem("token");
  if (token) {
    config.headers.Authorization = `Bearer ${token}`;
  }
  return config;
});

// An expired or invalid token means the session is over: clear it and go to the login page.
// (403 means "logged in but not allowed" and is left to the caller.)
apiClient.interceptors.response.use(
  (response) => response,
  (error) => {
    if (error.response?.status === 401 && localStorage.getItem("token")) {
      localStorage.removeItem("token");
      localStorage.removeItem("user");
      if (window.location.pathname !== "/login") {
        window.location.assign("/login");
      }
    } else if (error.message === "Network Error") {
      console.error("Network error:", error);
    }
    return Promise.reject(error);
  }
);

/** Best human readable message for a failed request. */
export const getErrorMessage = (error, fallback = "Something went wrong.") =>
  error?.response?.data?.message || error?.response?.data?.error || fallback;

